#!/usr/bin/env python3
"""Write a call chain as a Pawn program: f0 calls f1 calls ... f{N-1}.

Each function has a local array of deterministic, varied size; main calls f0.

  gen_chain.py --length 2000 > out.pwn
"""
import argparse
import sys

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--length', type=int, required=True)
    args = ap.parse_args()
    n = args.length
    out = ['// Generated by bench/stack-estimate/gen_chain.py --length %d' % n,
           '// Call chain of %d functions.' % n, '']
    for i in range(n):
        k = (i * 5) % 17 + 1
        calls = 'f%d()' % (i + 1) if i + 1 < n else '1'
        out.append('f%d() { new a[%d]; a[0] = %s; return a[0]; }' % (i, k, calls))
    out += ['', 'main()', '{', '\tf0();', '}', '']
    sys.stdout.buffer.write('\n'.join(out).encode())

if __name__ == '__main__':
    main()
