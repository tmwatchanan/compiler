#!/usr/bin/env python3
"""Write a program with mutual-recursion rings on top of a layered DAG.

R rings of K functions: ring function i calls ring function (i+1) mod K, so each
ring is one cycle (one function per ring also calls itself). Every ring function
also calls all functions of layer 0 of a layered DAG (L layers x W functions,
each layer calls all of the next, like gen_layered.py). main calls one function
of each ring.

  gen_recursive.py --rings 4 --ring-size 6 --layers 8 --width 4 > out.pwn
"""
import argparse
import sys

def size(i, j):
    # local array size: varied, deterministic
    return (i * 7 + j * 3) % 13 + 1

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rings', type=int, required=True)
    ap.add_argument('--ring-size', type=int, required=True)
    ap.add_argument('--layers', type=int, required=True)
    ap.add_argument('--width', type=int, required=True)
    a = ap.parse_args()
    R, K, L, W = a.rings, a.ring_size, a.layers, a.width
    out = ['// Generated by bench/stack-estimate/gen_recursive.py --rings %d --ring-size %d --layers %d --width %d'
           % (R, K, L, W), '']
    # Forward declarations: the ring functions call each other before definition.
    for r in range(R):
        for i in range(K):
            out.append('forward R%d_%d();' % (r, i))
    out.append('')
    # Layered DAG
    for i in range(L):
        for j in range(W):
            calls = ' + '.join('L%d_%d()' % (i + 1, k) for k in range(W)) if i + 1 < L else '1'
            out.append('L%d_%d() { new a[%d]; a[0] = %s; return a[0]; }' % (i, j, size(i, j), calls))
    out.append('')
    layer0 = ' + '.join('L0_%d()' % j for j in range(W))
    for r in range(R):
        for i in range(K):
            calls = ['R%d_%d()' % (r, (i + 1) % K), layer0]
            if i == 0:
                calls.append('R%d_0()' % r)  # self call
            out.append('R%d_%d() { new a[%d]; a[0] = %s; return a[0]; }'
                       % (r, i, size(r + 1, i) + 2, ' + '.join(calls)))
    out += ['', 'main()', '{']
    out += ['\tR%d_0();' % r for r in range(R)]
    out += ['}', '']
    sys.stdout.buffer.write('\n'.join(out).encode())

if __name__ == '__main__':
    main()
