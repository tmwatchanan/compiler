#!/usr/bin/env python3
"""Write a layered call graph as a Pawn program.

Every function of layer i calls every function of layer i+1, so the number of
call paths is width**layers while there are only layers*width functions. The
old stack estimate followed every path; this shape shows whether shared callees
are computed once.

  gen_layered.py --layers 40 --width 4 > out.pwn
"""
import argparse
import sys

def size(i, j):
    # local array size of function j in layer i: varied, deterministic
    return (i * 7 + j * 3) % 13 + 1

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--layers', type=int, required=True)
    ap.add_argument('--width', type=int, required=True)
    args = ap.parse_args()
    L, W = args.layers, args.width
    out = ['// Generated by bench/stack-estimate/gen_layered.py --layers %d --width %d' % (L, W),
           '// Layered call graph: %d functions, %d**%d call paths.' % (L * W, W, L), '']
    for i in range(L):
        for j in range(W):
            if i + 1 < L:
                calls = ' + '.join('L%d_%d()' % (i + 1, k) for k in range(W))
            else:
                calls = '1'
            out.append('L%d_%d() { new a[%d]; a[0] = %s; return a[0]; }' % (i, j, size(i, j), calls))
    out += ['', 'main()', '{']
    out += ['\tL0_%d();' % j for j in range(W)]
    out += ['}', '']
    sys.stdout.buffer.write('\n'.join(out).encode())

if __name__ == '__main__':
    main()
